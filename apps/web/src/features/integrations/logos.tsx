/** `size` is the tile: 32 in lists, 40 in a page header; the mark is 60% of it. */
export function ProviderLogo({ kind, size = 32 }: ProviderLogo.Props) {
  const mark = MARKS[kind]
  const inner = Math.round(size * 0.6)
  return (
    <span
      className={styles.logo}
      style={{ width: size, height: size }}
      data-kind={kind}
      data-size={size}
      aria-hidden="true"
    >
      {mark ? (
        <svg width={inner} height={inner} viewBox={mark.viewBox} focusable="false">
          {mark.body}
        </svg>
      ) : (
        <span className={styles.logoLetter}>{kind.slice(0, 1).toUpperCase()}</span>
      )}
    </span>
  )
}

export namespace ProviderLogo {
  export interface Props {
    kind: Integration.Item['kind']
    size?: 24 | 32 | 40
  }
}
