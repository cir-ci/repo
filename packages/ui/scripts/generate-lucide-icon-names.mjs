// Writes packages/core/src/team/lucide-icon-names.ts from the installed lucide-react's icon names.
// `@circi/core` may not import lucide, so the server validates a team's icon against this copy;
// apps/web/test/lib/team-appearance.test.ts fails when it drifts. Run after a lucide-react
// upgrade: `pnpm icons:generate` (then `pnpm format`).
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

import { iconNames } from 'lucide-react/dynamic.mjs'

const target = resolve(import.meta.dirname, '../../core/src/team/lucide-icon-names.ts')
const names = [...new Set(iconNames)].toSorted((a, b) => (a < b ? -1 : a > b ? 1 : 0))

const lines = [
  '// GENERATED by packages/ui/scripts/generate-lucide-icon-names.mjs (`pnpm icons:generate`): do not edit.',
  "// Every icon name of the installed lucide-react, sorted. A team's icon must be one of these.",
  '',
  'export const LUCIDE_ICON_NAMES: readonly string[] = [',
  ...names.map((n) => `  '${n}',`),
  ']',
  '',
]
writeFileSync(target, lines.join('\n'))
console.log(`${names.length} icon names written to ${target}`)
